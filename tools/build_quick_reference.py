# Fills the Keywords section of quick-reference.html from data/keywords.js.
# Run from the repo folder:  python tools/build_quick_reference.py
import re, pathlib, html
root = pathlib.Path(__file__).resolve().parent.parent
kw = (root / "data" / "keywords.js").read_text(encoding="utf-8")
items = []
for m in re.finditer(r'^KW\("[^"]*",\s*"([^"]*)",\s*\[(.*?)\]\s*\);', kw, re.M | re.S):
    name = m.group(1)
    rules = re.findall(r'"((?:[^"\\]|\\.)*)"', m.group(2))
    text = " ".join(r.replace('\\"', '"') for r in rules)
    items.append((name, text))
items.sort(key=lambda x: x[0].lower())
body = "\n".join('<div><dt>%s</dt> <dd>%s</dd></div>' % (html.escape(n), html.escape(t)) for n, t in items)
page = (root / "quick-reference.html").read_text(encoding="utf-8")
start = "<!-- KEYWORDS START (generated by tools/build_quick_reference.py - don't edit by hand) -->"
end = "<!-- KEYWORDS END -->"
i, j = page.index(start) + len(start), page.index(end)
page = page[:i] + "\n" + body + "\n" + page[j:]
(root / "quick-reference.html").write_text(page, encoding="utf-8")
print("Wrote %d keywords into quick-reference.html" % len(items))
